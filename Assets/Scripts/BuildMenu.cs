using UnityEngine;
using System.Collections;

public class BuildMenu : MonoBehaviour {    
    public int width = 200;
    public int height = 35;

    public GameObject prefab;
    
    GameObject instance;

    void Update() {
        // Ошибка: место для замка выбрать нельзя, он ставится сразу.
        //
        // Что видит игрок. Нажал BUILD CASTLE — замок тут же встаёт под курсором,
        // часто прямо под кнопкой. По карте его не перетащить.
        //
        // Почему. GetMouseButton(0) истинно всё время, пока левая кнопка зажата,
        // а не только в момент нового щелчка. Кнопку меню нажимают этой же кнопкой.
        // Замок создаётся в OnGUI, а уже на следующем кадре (следующем вызове Update)
        // игра видит «кнопка всё ещё зажата» и делает instance = null.
        // instance — это ссылка «замок, который сейчас двигаем». Когда она null,
        // двигать больше нечего, замок остаётся в мире там, где успел появиться.
        //
        // Как исправить. Подтверждать постановку только в момент нового щелчка,
        // а не всё время, пока кнопка зажата. Щелчок по самой кнопке меню
        // не считать выбором места. Проще всего запомнить кадр, когда замок
        // создали, и начать слушать клик только со следующего кадра.
        //
        // Вторая ошибка в этом же методе: замок замирает и не едет за мышкой.
        // Луч из камеры попадает в первый предмет на пути. Как только замок
        // оказался под курсором, луч бьёт в него самого, а не в землю.
        // Условие имени "Ground" ложно, позицию больше не обновляют.
        // Коллайдер — невидимая оболочка объекта, в которую попадают клики и лучи.
        //
        // Как исправить. Пока замок двигают, выключить его коллайдер
        // и включить обратно, когда место уже выбрано. Либо пускать луч
        // только в слой земли, чтобы он не замечал сам замок.
        //
        // Третья ошибка: призрак — уже настоящий замок. На нём висят скрипты
        // жизни и спавна и тег Player, поэтому враги стреляют по нему сразу,
        // а клик по нему ещё и создаёт солдата (см. CastlePlayer.OnMouseDown).
        //
        // Как исправить. Водить по карте пустую модель без этих скриптов и без тега.
        // Настоящий замок создавать один раз, в момент подтверждения места.
        if (instance != null) {
            Ray ray = Camera.main.ScreenPointToRay(Input.mousePosition);
            RaycastHit hit;
            if (Physics.Raycast(ray, out hit)) {
                if (hit.transform.name == "Ground") {
                    instance.transform.position = hit.point;
                    

                }
            }
            

            if (Input.GetMouseButton(0)) {
                instance = null;
            }
        }
    }
    
    void OnGUI() {
        GUILayout.BeginArea(new Rect(Screen.width/2 - width/2,
                                     Screen.height - height,
                                     width,
                                     height), "", "box");
        

        // Ошибка: пока выбираешь место для замка, пропадает рамка выделения юнитов.
        //
        // Почему. GUI.enabled — один выключатель на все нарисованные через OnGUI
        // элементы, не только на эту кнопку. Его выключают, чтобы BUILD CASTLE
        // нельзя было нажать второй раз, и забывают включить обратно.
        // Чужой код в Selection.OnGUI тоже перестаёт рисоваться.
        //
        // Как исправить. Сразу после кнопки снова включить общий выключатель
        // интерфейса, чтобы чужие элементы тоже рисовались.
        GUI.enabled = (instance == null);
        if (GUILayout.Button("BUILD CASTLE")) {
            instance = (GameObject)GameObject.Instantiate(prefab);
        }
        GUILayout.EndArea();
    }
}