using UnityEngine;
using System.Collections;

public class CastlePlayer : MonoBehaviour {       
    void OnMouseDown() {
        // Ошибка: щелчок, которым ставят замок, заодно создаёт солдата.
        // Тот же щелчок снимает выделение с уже выбранного отряда.
        //
        // Почему. OnMouseDown вызывается на любой клик по оболочке замка.
        // Призрак из BuildMenu — это тот же замок, поэтому клик «поставить сюда»
        // попадает и сюда, в spawn(). Selection в этот момент видит клик
        // без протяжки мыши и гасит кружки выделения у всех (см. Selection.cs).
        //
        // Как исправить. Не создавать солдата, пока игрок ещё выбирает место
        // для замка. Например, завести признак «сейчас строим» и здесь
        // сразу выходить, если он включён. Снятие выделения чинится
        // отдельно, в Selection: короткий клик должен выбирать одного юнита,
        // а не сбрасывать всех.
        if (!GetComponent<AnimationSinus>().inProgress()) {            
            GetComponent<UnitSpawner>().spawn();
        }
    }
}